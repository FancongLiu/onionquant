def _make_demo_data() -> dict:
    """Create demo data covering all report inputs."""
    rng = np.random.default_rng(42)
    n = 252
    dates = pd.date_range("2024-01-01", periods=n, freq="B")
    tickers = ["AAPL", "MSFT", "GOOGL", "AMZN", "NVDA", "META", "TSLA", "JPM"]

    returns = pd.Series(rng.normal(0.001, 0.018, n), index=dates)
    equity = (1 + returns).cumprod() * 1_000_000

    signals = pd.DataFrame(
        {
            "ticker": np.tile(tickers, 5),
            "signal": rng.choice([-1, 0, 1], len(tickers) * 5, p=[0.2, 0.4, 0.4]),
            "combined_score": rng.normal(0, 1, len(tickers) * 5),
        }
    )

    positions = pd.DataFrame(
        {
            "ticker": tickers[:5],
            "shares": rng.integers(100, 5000, 5),
            "weight": [0.30, 0.25, 0.20, 0.15, 0.10],
            "value": rng.integers(10000, 500000, 5),
        }
    )

    factor_ic = pd.DataFrame(
        {
            "factor": [f"factor_{i}" for i in range(8)],
            "mean_ic": rng.normal(0.02, 0.03, 8),
            "ic_ir": np.abs(rng.normal(0.5, 0.3, 8)),
            "hit_rate": rng.uniform(0.5, 0.7, 8),
            "ic_decay_days": rng.uniform(3, 30, 8),
        }
    ).sort_values("mean_ic", ascending=False)

    risk_summary = {
        "Sharpe": 1.35,
        "Sortino": 1.82,
        "Calmar": 0.95,
        "MaxDD": -0.15,
        "VaR_95": -0.022,
        "CVaR_95": -0.031,
    }

    attribution = {
        "r_squared": 0.88,
        "alpha_annual": 0.045,
        "exposures": {"MKT": 1.02, "SMB": 0.28, "HML": -0.15, "MOM": 0.12},
        "t_statistics": {"MKT": 45.3, "SMB": 8.7, "HML": -5.2, "MOM": 4.1},
        "factor_contributions": {
            "MKT": 0.0005,
            "SMB": 0.0002,
            "HML": -0.0001,
            "MOM": 0.0001,
        },
    }

    stress = {
        "stress_score": -0.18,
        "worst_scenario": "2008 GFC",
        "scenarios": [
            {
                "scenario": "2020 COVID Crash",
                "total_return": -0.25,
                "max_drawdown": -0.34,
                "var_95": -0.06,
            },
            {
                "scenario": "2008 GFC",
                "total_return": -0.32,
                "max_drawdown": -0.50,
                "var_95": -0.08,
            },
        ],
    }

    tca = {"avg_is_bp": 3.2, "avg_vwap_slippage_bp": -1.5, "n_trades": 42}

    return {
        "signals": signals,
        "positions": positions,
        "pnl": returns * 50000,
        "factor_ic": factor_ic,
        "returns": returns,
        "equity_curve": equity,
        "risk_summary": risk_summary,
        "attribution": attribution,
        "stress_result": stress,
        "tca_summary": tca,
        "factor_analysis": {"ic_summary": factor_ic},
    }


def main():
    data = _make_demo_data()
    config = ReportConfig(output_dir="company/reports")

    daily = generate_daily_briefing(
        signals=data["signals"],
        positions=data["positions"],
        pnl=data["pnl"],
        factor_ic=data["factor_ic"],
        config=config,
    )
    print(daily[:800])
    print("\n...\n")

    monthly = generate_monthly_report(
        returns=data["returns"],
        equity_curve=data["equity_curve"],
        attribution=data["attribution"],
        stress_result=data["stress_result"],
        tca_summary=data["tca_summary"],
        factor_analysis=data["factor_analysis"],
        config=config,
    )
    print(monthly[:800])

    # Save reports
    _, dp = generate_full_report(
        "daily", signals=data["signals"], positions=data["positions"], pnl=data["pnl"]
    )
    _, mp = generate_full_report(
        "monthly", returns=data["returns"], attribution=data["attribution"]
    )
    print(f"\nSaved: {dp}")
    print(f"Saved: {mp}")


def export_pdf(
    markdown_content: str, output_path: str, title: str = "Quant Report"
) -> str:
    """Export a markdown report to PDF using weasyprint (T877).

    Converts markdown → HTML → PDF with basic styling.
    Requires: pip install weasyprint
    """
    try:
        from weasyprint import HTML
    except ImportError:
        raise ImportError("weasyprint not installed. Run: pip install weasyprint")

    # Minimal markdown → HTML conversion (handles basic markdown tables/lists/headers)
    html_body = _markdown_to_html(markdown_content)
    html = f"""<!DOCTYPE html>
<html lang="en">
<head><meta charset="UTF-8"><title>{title}</title>
<style>
  body {{ font-family: 'Segoe UI', Arial, sans-serif; max-width: 800px; margin: 0 auto; padding: 20px; color: #1a1a1a; }}
  h1 {{ color: #0a0e17; border-bottom: 2px solid #f0b90b; padding-bottom: 8px; }}
  h2 {{ color: #1e293b; margin-top: 24px; }}
  table {{ border-collapse: collapse; width: 100%; margin: 12px 0; }}
  th {{ background: #1e293b; color: #e2e8f0; padding: 8px 12px; text-align: left; }}
  td {{ padding: 6px 12px; border-bottom: 1px solid #e2e8f0; }}
  .positive {{ color: #10b981; }} .negative {{ color: #ef4444; }}
  code {{ background: #f1f5f9; padding: 2px 6px; border-radius: 4px; }}
  pre {{ background: #1e293b; color: #e2e8f0; padding: 16px; border-radius: 8px; overflow-x: auto; }}
</style></head><body>{html_body}</body></html>"""

    HTML(string=html).write_pdf(output_path)
    return output_path


def _markdown_to_html(md: str) -> str:
    """Basic markdown → HTML for PDF export (no external deps)."""
    lines = md.split("\n")
    html_lines = []
    in_table = False
    in_code = False

    for line in lines:
        # Code blocks
        if line.startswith("```"):
            if in_code:
                html_lines.append("</pre>")
                in_code = False
            else:
                html_lines.append("<pre>")
                in_code = True
            continue
        if in_code:
            html_lines.append(line)
            continue

        # Headers
        if line.startswith("#### "):
            html_lines.append(f"<h4>{line[5:]}</h4>")
            continue
        if line.startswith("### "):
            html_lines.append(f"<h3>{line[4:]}</h3>")
            continue
        if line.startswith("## "):
            html_lines.append(f"<h2>{line[3:]}</h2>")
            continue
        if line.startswith("# "):
            html_lines.append(f"<h1>{line[2:]}</h1>")
            continue

        # Table rows
        if line.startswith("|") and line.endswith("|"):
            cells = [c.strip() for c in line[1:-1].split("|")]
            is_sep = all(
                c.replace("-", "").replace(":", "").strip() == "" for c in cells
            )
            if not in_table:
                html_lines.append("<table>")
                in_table = True
            if is_sep:
                continue  # skip separator row
            tag = (
                "th"
                if in_table and not any("<td>" in line for line in html_lines[-3:])
                else "td"
            )
            html_lines.append(
                "<tr>" + "".join(f"<{tag}>{c}</{tag}>" for c in cells) + "</tr>"
            )
            continue
        elif in_table:
            html_lines.append("</table>")
            in_table = False

        # Bold
        import re

        line = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", line)
        # Italic
        line = re.sub(r"\*(.+?)\*", r"<em>\1</em>", line)
        # Inline code
        line = re.sub(r"`(.+?)`", r"<code>\1</code>", line)

        if line.strip():
            html_lines.append(f"<p>{line}</p>")
        else:
            html_lines.append("<br>")

    if in_table:
        html_lines.append("</table>")
    if in_code:
        html_lines.append("</pre>")

    return "\n".join(html_lines)


if __name__ == "__main__":
    main()
